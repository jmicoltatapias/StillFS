CREATE TABLE principals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE credentials (
    access_key_id TEXT COLLATE "C" PRIMARY KEY,
    principal_id BIGINT NOT NULL,
    secret_ciphertext BYTEA NOT NULL,
    secret_nonce BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at TIMESTAMPTZ,
    CONSTRAINT credentials_access_key_not_empty CHECK (access_key_id <> ''),
    CONSTRAINT credentials_secret_ciphertext_size CHECK (octet_length(secret_ciphertext) >= 16),
    CONSTRAINT credentials_secret_nonce_size CHECK (octet_length(secret_nonce) = 12),
    CONSTRAINT credentials_principal_fk FOREIGN KEY (principal_id)
        REFERENCES principals (id) ON DELETE RESTRICT
);

ALTER TABLE buckets
    ADD COLUMN owner_id BIGINT,
    ADD CONSTRAINT buckets_owner_fk FOREIGN KEY (owner_id)
        REFERENCES principals (id) ON DELETE RESTRICT;

CREATE INDEX buckets_owner_name_idx ON buckets (owner_id, name);
