CREATE TABLE buckets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT COLLATE "C" NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT buckets_name_unique UNIQUE (name),
    CONSTRAINT buckets_name_not_empty CHECK (name <> '')
);

CREATE TABLE objects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bucket_id BIGINT NOT NULL,
    object_key TEXT COLLATE "C" NOT NULL,
    storage_ref TEXT NOT NULL,
    size_bytes BIGINT NOT NULL,
    content_type TEXT,
    etag TEXT,
    checksum_algorithm TEXT,
    checksum_value TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT objects_bucket_key_unique UNIQUE (bucket_id, object_key),
    CONSTRAINT objects_bucket_fk FOREIGN KEY (bucket_id)
        REFERENCES buckets (id) ON DELETE RESTRICT,
    CONSTRAINT objects_storage_ref_not_empty CHECK (storage_ref <> ''),
    CONSTRAINT objects_size_nonnegative CHECK (size_bytes >= 0),
    CONSTRAINT objects_checksum_pair CHECK (
        (checksum_algorithm IS NULL) = (checksum_value IS NULL)
    )
);

CREATE INDEX objects_bucket_prefix_idx
    ON objects (bucket_id, object_key text_pattern_ops);
